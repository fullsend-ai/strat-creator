def edit(batch):
    root, _, jira = batch
    jira.request('PUT', '/rest/api/3/issue/RHAIRFE-8902', {'fields': {
        'description': markdown_to_adf('New constraint added after refinement.')}})
    return root


def review(root, key):
    prepare(root, key, key.replace('RHAISTRAT', 'RHAIRFE'), (1, 1, 1, 1))
    value = subprocess.run([sys.executable, str(ROOT / 'scripts/publish_review.py'), key],
                           cwd=root, capture_output=True, text=True, timeout=60)
    assert value.returncode == 0, value.stderr
    command(root, 'record-review', key)


def test_mid_batch_edit_allows_other_review_and_host_publication(batch):
    root = edit(batch)
    review(root, 'RHAISTRAT-8901')
    command(root, 'result')
    result = json.loads((root / 'output/agent-result.json').read_text())
    assert result['action'] == 'completed', result['errors']
    assert [v['strat'] for v in result['strategies']] == ['RHAISTRAT-8901']
    assert [v['key'] for v in result['deferred']] == ['RHAIRFE-8902']
    assert all('8902' not in path for path in result['artifacts'])
    run_file = root / 'host-run.json'
    run_file.write_text(json.dumps(batch[1]))
    check = subprocess.run([sys.executable, str(ROOT / '.fullsend/shared/validate_result.py'),
                            '--result', str(root / 'output/agent-result.json'), '--repo', str(root),
                            '--schema', str(ROOT / '.fullsend/shared/result.schema.json'),
                            '--run', str(run_file)], capture_output=True, text=True, timeout=60)
    assert check.returncode == 0, check.stdout + check.stderr
    assert not get_comments(batch[2].url, 'admin', 'admin', 'RHAISTRAT-8902')
    handoff, bundle = root / 'handoff', root / 'bundle'
    copy = subprocess.run([sys.executable, str(ROOT / '.fullsend/shared/handoff.py'), str(root),
                           str(handoff), str(root / 'output/agent-result.json')],
                          capture_output=True, text=True, timeout=60)
    assert copy.returncode == 0, copy.stderr
    publish = subprocess.run([sys.executable, str(ROOT / '.fullsend/shared/prepare_publication.py'),
                              str(handoff), str(bundle), str(root / 'output/agent-result.json'),
                              'pipeline-settings'], capture_output=True, text=True, timeout=60)
    assert publish.returncode == 0, publish.stdout + publish.stderr
    assert not list(bundle.rglob('*8902*'))
    exported = json.loads((bundle / 'pipeline-data.json').read_text())
    assert [v['strat_id'] for v in exported['strategies']] == ['RHAISTRAT-8901']
    assert exported['deferred'] == result['deferred']


