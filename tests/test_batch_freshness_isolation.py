def batch(tmp_path, jira, monkeypatch, request):
    monkeypatch.chdir(tmp_path)
    for key, value in {'JIRA_SERVER': jira.url, 'JIRA_USER': 'admin', 'JIRA_TOKEN': 'admin'}.items():
        monkeypatch.setenv(key, value)
    pairs = [('RHAIRFE-8901', 'RHAISTRAT-8901'), ('RHAIRFE-8902', 'RHAISTRAT-8902')]
    data = {'run_id': 'batch-drift', 'lock_owner': 'batch-drift', 'mode': 'batch', 'dry_run': False,
            'input_keys': [rfe for rfe, _ in pairs], 'acquired_keys': [rfe for rfe, _ in pairs],
            'expected_skips': [], 'skipped': [], 'resume_points': {}, 'architecture_context': 'available'}
    (tmp_path / 'tmp').mkdir()
    (tmp_path / 'scripts').mkdir()
    (tmp_path / 'scripts/rules.py').write_text('# Checked source.\n')
    for rfe, key in pairs:
        jira.create(rfe, 'Independent need ' + rfe, 'Original requirement.',
                    labels=['strat-creator-processing', owner_label(data['run_id'])])
        jira.create(key, 'Strategy ' + key, 'Original business need.', issue_type='Feature',
                    labels=['strat-creator-auto-created'])
        jira.request('POST', '/rest/api/3/issueLink', {'type': {'name': 'Cloners'},
                     'inwardIssue': {'key': key}, 'outwardIssue': {'key': rfe}})
        task = tmp_path / f'artifacts/strat-tasks/{key}.md'
        task.parent.mkdir(parents=True, exist_ok=True)
        task.write_text('## Strategy (AI Generated by Agentic SDLC Pipeline)\n'
                        'Use the existing controller with bounded request timeouts.\n')
