def test_unreadable_live_input_produces_failed_receipt_without_approving_it(batch, monkeypatch):
    import strat_freshness
    import strat_pipeline_state as state
    from strat_pipeline_outcome import verify_completion
    root = batch[0]
    real = strat_freshness.jira_rfe

    def unavailable(key):
        if key == 'RHAIRFE-8902':
            raise OSError('Cannot read the second RFE.')
        return real(key)

    monkeypatch.setattr(strat_freshness, 'jira_rfe', unavailable)
    monkeypatch.setenv('FULLSEND_OUTPUT_DIR', str(root / 'output'))
    state.main(['result'])
