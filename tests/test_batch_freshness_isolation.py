def command(root, *args, check=True):
    value = subprocess.run([sys.executable, str(ROOT / 'scripts/strat_pipeline_state.py'), *args],
                           cwd=root, env={**os.environ, 'FULLSEND_OUTPUT_DIR': str(root / 'output')},
                           capture_output=True, text=True, timeout=60)
    if check:
        assert value.returncode == 0, value.stderr
    return value


