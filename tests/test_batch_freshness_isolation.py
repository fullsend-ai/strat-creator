@pytest.mark.parametrize('fault', ['source', 'architecture'])
def test_shared_source_failure_still_produces_failed_completion(batch, fault):
    root = batch[0]
    path = root / ('scripts/rules.py' if fault == 'source' else '.context/architecture-context/rules.md')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('# Changed during this run.\n')
    response = command(root, 'result', '--failed', 'workflow')
    final = json.loads(response.stdout)
    assert final['action'] == 'failed' and final['check_exit'] == 1
    from strat_pipeline_outcome import guard
    event = {'cwd': str(root), 'hook_event_name': 'PreToolUse', 'tool_name': 'StructuredOutput',
             'tool_input': final}
    assert guard(event) == final
    result = json.loads((root / 'output/agent-result.json').read_text())
    expected = 'source/instructions' if fault == 'source' else 'architecture files'
    assert any(expected in error for error in result['errors'])


def test_edit_during_role_reviews_preserves_other_ticket(batch):
    from review_composition import capture, compose
    from strat_freshness import StaleTicket
    root = batch[0]
    _, reports = prepare(root, 'RHAISTRAT-8902', 'RHAIRFE-8902', (1, 1, 1, 1), finish=False)
    capture(reports['scope'])
    capture(reports['feasibility'])
