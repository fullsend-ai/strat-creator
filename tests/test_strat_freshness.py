@pytest.mark.parametrize("change", ["rfe_description", "rfe_comment", "rfe_gate", "staff"])
def test_live_source_changes_stop_publication(live, monkeypatch, change):
    repo, data, jira = live
    if change == "rfe_description":
        jira.request("PUT", "/rest/api/3/issue/RHAIRFE-8801", {"fields": {"description": markdown_to_adf("New RFE.")}})
    elif change == "rfe_comment":
        jira.request("POST", "/rest/api/3/issue/RHAIRFE-8801/comment", {"body": markdown_to_adf("New constraints.")})
    elif change == "rfe_gate":
        jira.request("PUT", "/rest/api/3/issue/RHAIRFE-8801", {"update": {"labels": [{"add": "changed-scope"}]}})
    else:
        jira.request("PUT", "/rest/api/3/issue/RHAISTRAT-8801", {"fields": {
            "description": markdown_to_adf("## Staff Engineer / SME Input\nUse another component.\n")}})
    before = (repo / "tmp/strat-progress.json").read_bytes()
    monkeypatch.chdir(repo)
    with pytest.raises(ValueError, match="freshness"):
        add_comment(jira.url, "admin", "admin", "RHAISTRAT-8801", markdown_to_adf("Should not publish."))
    assert not get_comments(jira.url, "admin", "admin", "RHAISTRAT-8801")
    assert (repo / "tmp/strat-progress.json").read_bytes() == before


def push(live):
    repo, data, _ = live
    result = subprocess.run([sys.executable, str(ROOT / "scripts/push_strategy.py"), "RHAISTRAT-8801",
                             "artifacts/strat-tasks/RHAISTRAT-8801.md"], cwd=repo, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    marked = command(repo, "mark", "push")
    assert marked.returncode == 0, marked.stderr
    return repo, data, json.loads((repo / "tmp/strat-progress.json").read_text())


def test_verified_push_reuses_unchanged_inputs_in_later_job(live):
    repo, data, progress = push(live)
    verify_progress(repo, data, progress)
    result = reusable(repo, "RHAIRFE-8801", "RHAISTRAT-8801", progress, trusted_source=ROOT)
    assert result and result["previous_run_id"] == data["run_id"]
    # Another run receives its own parameters but the same input context.
    next_data = {k: v for k, v in data.items() if k != "freshness"}
    next_data.update(run_id="next-run", reused_push={"RHAIRFE-8801": result})
    initialize(repo, next_data, live=True, trusted_source=ROOT)
    verify(repo, next_data, trusted_source=ROOT)


@pytest.mark.parametrize("change", ["source", "overlay", "rfe", "published", "legacy"])
def test_later_job_does_not_reuse_stale_push(live, change):
    repo, _, progress = push(live)
    jira = live[2]
    if change == "source":
        (repo / "scripts/refinement.py").write_text("New instructions.\n")
    elif change == "overlay":
        (repo / ".context/architecture-context/overlays/ownership.md").write_text("Changed ownership.\n")
    elif change == "rfe":
        jira.request("PUT", "/rest/api/3/issue/RHAIRFE-8801", {"fields": {"description": markdown_to_adf("New RFE.")}})
    elif change == "published":
        jira.request("PUT", "/rest/api/3/issue/RHAISTRAT-8801", {"fields": {
            "description": markdown_to_adf("Human edited the published strategy.")}})
    else:
        progress.pop("freshness")
    assert reusable(repo, "RHAIRFE-8801", "RHAISTRAT-8801", progress, trusted_source=ROOT) is None
