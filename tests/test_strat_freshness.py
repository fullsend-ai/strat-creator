def command(repo, *args, env=None):
    values = {**os.environ, "FULLSEND_OUTPUT_DIR": str(repo / "output"), **(env or {})}
    result = subprocess.run([sys.executable, str(ROOT / "scripts/strat_pipeline_state.py"), *args],
                            cwd=repo, env=values, capture_output=True, text=True, timeout=60)
    log = repo / f"check-{len(list(repo.glob('check-*.json')))}.json"
    log.write_text(json.dumps({"args": args, "exit": result.returncode,
                              "stdout": result.stdout, "stderr": result.stderr}, indent=2))
    return result


def seed(repo, live=False):
    for rel, content in {
        "scripts/refinement.py": "# authored source version 1\n",
        "scripts/assess-strat/agent_prompt.md": "Authored scoring instructions.\n",
        ".claude/skills/strategy-refine/SKILL.md": "Authored refinement instructions.\n",
        "workflows/strat-pipeline.js": "// authored workflow version 1\n",
        ".context/architecture-context/overlays/ownership.md": "Router owns timeouts.\n",
    }.items():
        path = repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    data = {"run_id": "freshness-run", "mode": "single", "dry_run": False,
            "input_keys": ["RHAIRFE-8801"], "acquired_keys": ["RHAIRFE-8801"], "expected_skips": [],
            "resume_points": {}, "skipped": [], "architecture_context": "available"}
    initialize(repo, data, live=live, trusted_source=ROOT)
    (repo / "tmp").mkdir()
    (repo / "tmp/strat-input.json").write_text(json.dumps(data))
    task = repo / "artifacts/strat-tasks/RHAISTRAT-8801.md"
    task.parent.mkdir(parents=True)
    task.write_text("## Strategy (AI Generated by Agentic SDLC Pipeline)\n\n"
                    "### Technical Approach\nThe router cancels requests at the configured deadline.\n")
    write_frontmatter(task, {"strat_id": "RHAISTRAT-8801", "source_rfe": "RHAIRFE-8801",
                            "jira_key": "RHAISTRAT-8801", "title": "Timeout ownership", "priority": "Major",
                            "status": "Refined"}, "strat-task")
    original = repo / "artifacts/strat-originals/RHAIRFE-8801.md"
    original.parent.mkdir()
    original.write_text("Users need bounded request latency.\n")
    return data


@pytest.fixture
def ready(tmp_path):
    data = seed(tmp_path)
    assert command(tmp_path, "record-create").returncode == 0
    assert command(tmp_path, "mark", "refine", "RHAISTRAT-8801").returncode == 0
    # Preserve an uncertain write as evidence while testing rejection paths.
    path = tmp_path / "tmp/strat-effects/pending.json"
    path.parent.mkdir()
    path.write_text('{"status":"pending","identity":{}}')
    return tmp_path, data


@pytest.mark.parametrize("relative", [
    "scripts/refinement.py", "scripts/assess-strat/agent_prompt.md", ".claude/skills/strategy-refine/SKILL.md",
    "workflows/strat-pipeline.js", ".context/architecture-context/overlays/ownership.md",
    "artifacts/strat-originals/RHAIRFE-8801.md", "artifacts/strat-tasks/RHAISTRAT-8801.md",
])
def test_changed_input_stops_before_reuse_and_preserves_work(ready, relative):
    repo, _ = ready
    progress = (repo / "tmp/strat-progress.json").read_bytes()
    intent = (repo / "tmp/strat-effects/pending.json").read_bytes()
    path = repo / relative
    path.write_text(path.read_text() + "Changed input.\n")
    result = command(repo, "read")
    assert result.returncode == 1 and "freshness" in result.stderr
    assert (repo / "tmp/strat-progress.json").read_bytes() == progress
    assert (repo / "tmp/strat-effects/pending.json").read_bytes() == intent


@pytest.mark.parametrize("action", ["add", "delete"])
def test_overlay_inventory_change_is_detected(ready, action):
    repo, _ = ready
    if action == "add":
        (repo / ".context/architecture-context/overlays/new.md").write_text("New ownership rule.\n")
    else:
        (repo / ".context/architecture-context/overlays/ownership.md").unlink()
    assert command(repo, "read").returncode == 1


def test_unchanged_inputs_reuse_valid_marks_and_ignore_mtime(ready):
    repo, data = ready
    original = (repo / "tmp/strat-progress.json").read_bytes()
    (repo / "scripts/refinement.py").touch()
    result = command(repo, "read")
    assert result.returncode == 0, result.stderr
    assert json.loads(result.stdout)["refined"] == ["RHAISTRAT-8801"]
    verify_progress(repo, data, json.loads(original))
    assert (repo / "tmp/strat-progress.json").read_bytes() == original


def test_run_parameters_and_missing_legacy_baseline_are_rejected(ready):
    repo, data = ready
    data["mode"] = "batch"
    (repo / "tmp/strat-input.json").write_text(json.dumps(data))
    assert "parameters changed" in command(repo, "read").stderr
    data.pop("freshness")
    marker = repo / ".claude-plugin/plugin.json"
    marker.parent.mkdir()
    marker.write_text('{"name":"strat-creator"}')
    (repo / "tmp/strat-input.json").write_text(json.dumps(data))
    assert "missing/legacy" in command(repo, "read").stderr


def test_native_replay_is_rejected_but_fresh_launch_checks_inputs(ready):
    repo, _ = ready
    event = {"cwd": str(repo), "tool_name": "Workflow", "tool_input": {"name": "strat-pipeline:strat-pipeline"}}
    guard(event)
    event["tool_input"]["resumeFromRunId"] = "old-native-run"
    with pytest.raises(ValueError, match="native journal replay"):
        guard(event)
    del event["tool_input"]["resumeFromRunId"]
    (repo / "scripts/refinement.py").write_text("Changed source.\n")
    with pytest.raises(ValueError, match="source/instructions"):
        guard(event)


