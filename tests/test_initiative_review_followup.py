def test_another_id_does_not_settle_a_shared_prefix_id():
    """7. With RHAIRFE-1, RHAISTRAT-2 may be an Initiative: a mixed list is not silently an RFE run."""
    assert type_registry.resolve(REG, ids=["RHAIRFE-1", "RHAISTRAT-2"], env={}).ambiguous
    with pytest.raises(type_registry.ResolveError):
        type_registry.resolve(REG, ids=["RHAIRFE-1", "RHAISTRAT-2"], env={"CI": "true"})
    assert type_registry.resolve(REG, ids=["RHAIRFE-1", "RHAIRFE-2"], env={"CI": "true"}).type_name == "rfe-strategy"
    pinned = type_registry.resolve(REG, explicit_type="rfe-strategy", ids=["RHAIRFE-1", "RHAISTRAT-2"], env={})
    assert pinned.type_name == "rfe-strategy"
