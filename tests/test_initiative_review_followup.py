def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


def _script(jira, script, *args):
    env = {**os.environ, **ENV, "JIRA_SERVER": jira.url}
    return subprocess.run([sys.executable, str(ROOT / "scripts" / script), *args],
                          capture_output=True, text=True, env=env)


def _labels(jira, key):
    return set(jira.get(key)["fields"]["labels"])


@pytest.mark.parametrize("run,ok", [({"type": "initiative-strategy"}, True), ({}, False)])
def test_the_validator_wants_no_clone_label_on_an_initiative(monkeypatch, run, ok):
    """1. Only the clone step writes strat-creator-auto-created; an Initiative is never cloned."""
    validator = module("followup_validate", ROOT / ".fullsend/shared/validate_result.py")
    labels = ["strat-creator-auto-refined", "strat-creator-rubric-pass"]
    monkeypatch.setattr(jira_utils, "require_env", lambda: ("s", "u", "t"))
    monkeypatch.setattr(jira_utils, "get_issue", lambda *a, **k: {"fields": {"labels": labels}})
    monkeypatch.setattr(validator, "verify_publication", lambda *a: None)
    monkeypatch.setitem(sys.modules, "find_strat_for_rfe", type(sys)("find_strat_for_rfe"))
    sys.modules["find_strat_for_rfe"].find_strat_clones = lambda *a: [{"key": "RHAISTRAT-7"}]
    key = "RHAISTRAT-7"
    result = {"strategies": [{"rfe": key if ok else "RHAIRFE-7", "strat": key, "recommendation": "approve"}]}
    checker = validator.Checker()
    validator.check_jira(checker, result, ROOT, run)
    missing = [f"{key} is missing Jira label(s) strat-creator-auto-created"]
    assert checker.failures == ([] if ok else missing)


