    def test_contains_doctype(self):
        html = self._render()
        assert "<!DOCTYPE html>" in html

    def test_css_body_rule(self):
        html = self._render()
        assert "body {" in html or "body{" in html

    def test_js_function_braces(self):
        html = self._render()
        assert "function " in html
        brace_count = html.count("function ")
        assert brace_count > 0
        assert "{" in html[html.index("function "):]

