"""The Workflow for a same-ticket type: an Initiative paired with itself, chosen by STRAT_TYPE."""
import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / ".fullsend/shared"))
STATE = ROOT / "scripts/strat_pipeline_state.py"
KEY = "RHAISTRAT-41"


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    loaded = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(loaded)
    return loaded


def _state(repo, *args):
    proc = subprocess.run([sys.executable, str(STATE), *args], cwd=repo, capture_output=True, text=True,
                          env={**os.environ, "FULLSEND_OUTPUT_DIR": str(repo / "output")})
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


@pytest.fixture
def repo(tmp_path):
    (tmp_path / "tmp").mkdir()
    (tmp_path / "tmp/strat-input.json").write_text(json.dumps({
        "run_id": "r1", "type": "initiative-strategy", "mode": "batch", "dry_run": True,
        "input_keys": [KEY], "acquired_keys": [KEY], "skipped": [], "resume_points": {KEY: "create"},
        "expected_skips": [], "architecture_context": "available"}))
    task = tmp_path / f"artifacts/strat-tasks/{KEY}.md"
    task.parent.mkdir(parents=True)
    task.write_text(f"---\nstrat_id: {KEY}\nsource_initiative: {KEY}\njira_key: {KEY}\ntitle: T\n"
                    "priority: Major\nstatus: Refined\ntype: initiative-strategy\n---\n"
                    "## Strategy (AI Generated by Agentic SDLC Pipeline)\nBody.\n")
    return tmp_path


def test_an_initiative_strategy_is_paired_with_its_own_ticket(repo):
    read = _state(repo, "read")
    assert read["type"] == "initiative-strategy" and read["pending_create"] == [KEY]
    created = _state(repo, "record-create")
    assert created == {"strategies": [{"rfe": KEY, "strat": KEY}], "skipped": [], "pending": []}
    assert _state(repo, "mark", "refine", KEY) == {"recorded": KEY}
    assert _state(repo, "refine-status")["refined"] == [KEY]


def test_an_rfe_key_is_not_an_initiative_run_input(repo):
    data = json.loads((repo / "tmp/strat-input.json").read_text())
    data["acquired_keys"] = ["RHAIRFE-1"]
    (repo / "tmp/strat-input.json").write_text(json.dumps(data))
    proc = subprocess.run([sys.executable, str(STATE), "read"], cwd=repo, capture_output=True, text=True)
    assert proc.returncode == 1 and "invalid key" in proc.stderr


def test_the_type_registry_gives_each_type_its_keys():
    import type_registry
    registry = type_registry.load()
    rfe, initiative = registry.get("rfe-strategy"), registry.get("initiative-strategy")
    assert rfe.input_key_re.match("RHAIRFE-1") and not rfe.input_key_re.match(KEY)
    assert rfe.strategy_key_re.match("RHAISTRAT-1") and rfe.strategy_key_re.match("STRAT-1")
    assert initiative.input_key_re.match(KEY) and initiative.strategy_key_re.match(KEY)
    assert initiative.same_ticket and not rfe.same_ticket
    assert type_registry.run_type({}).name == "rfe-strategy"


def test_reviewer_scope_follows_the_assigned_keys_type():
    import review_scope as scope
    assert scope.assignment(f"{scope.MARKER}{KEY}\n") == KEY
    with pytest.raises(scope.ScopeError):
        scope.assignment(f"{scope.MARKER}RHAIRFE-1\n")
    # RHAISTRAT keys are both types': the task file's type: stamp picks the Initiative's rules.
    initiative = scope.work_type(KEY, "initiative-strategy")
    assert initiative.name == "initiative-strategy" and scope.work_type(KEY).name == "rfe-strategy"
    own = {"key": KEY, "type": initiative, "source_rfe": KEY}
    scope.check_report(own, f"### {KEY}: Title\nFine.\n")
    with pytest.raises(scope.ScopeError, match="another strategy key"):
        scope.check_report(own, f"### {KEY}: Title\nLike RHAISTRAT-42.\n")
    with pytest.raises(scope.ScopeError, match="Return one assessment"):
        scope.check_report(own, "### ISTRAT-41: Title\nFine.\n")
    # An RFE strategy may cite engineering tickets.
    scope.check_report({"key": "RHAISTRAT-1", "source_rfe": "RHAIRFE-1"},
                       "### RHAISTRAT-1: Title\nFrom RHAIRFE-1, see RHOAIENG-42.\n")


@pytest.mark.parametrize("name,ignored", [("initiative-strategy", True), ("rfe-strategy", False)])
def test_freshness_ignores_only_a_same_ticket_runs_own_labels_and_comments(monkeypatch, name, ignored):
    import jira_utils
    import strat_freshness
    import type_registry
    work_type = type_registry.load().get(name)
    labels, comments = ["initiative-autofix-rubric-pass"], [{"id": "1", "body": "Owner note"}]
    monkeypatch.setattr(jira_utils, "require_env", lambda: ("s", "u", "t"))
    monkeypatch.setattr(jira_utils, "get_issue", lambda *a, **k: {"fields": {"labels": list(labels)}})
    monkeypatch.setattr(jira_utils, "get_comments", lambda *a: list(comments))
    before = strat_freshness.jira_rfe(KEY, work_type)
    labels.append("strat-creator-rubric-pass")
    comments.append({"id": "2", "body": jira_utils.markdown_to_adf("*[Strat Creator]* Strategy Review — APPROVE")})
    assert (strat_freshness.jira_rfe(KEY, work_type) == before) is ignored
    comments.append({"id": "3", "body": "A human changed the ask"})
    assert strat_freshness.jira_rfe(KEY, work_type) != before


def test_ci_checks_the_type_and_its_single_key():
    config = module("initiative_config", ROOT / ".fullsend/ci/fullsend-config.py")
    base = {"CI_PIPELINE_SOURCE": "web", "STRAT_TYPE": "initiative-strategy"}
    assert config.validate({**base, "RFE_KEY": KEY})["type"] == "initiative-strategy"
    for env, error in (({"RFE_KEY": "RHAIRFE-1"}, "RFE_KEY=RHAISTRAT-N"), ({"RFE_KEY": "RHAISTRAT-01"}, "RHAISTRAT-N"),
                       ({"STRAT_KEY": "RHAISTRAT-1"}, "single or batch mode only"),
                       ({"STRAT_TYPE": "nope"}, "STRAT_TYPE must be one of")):
        with pytest.raises(ValueError, match=error):
            config.validate({**base, **env})


def test_validator_checks_keys_against_the_run_type():
    validator = module("initiative_validate", ROOT / ".fullsend/shared/validate_result.py")
    result = {"input_keys": [KEY], "acquired_keys": [KEY], "skipped": [],
              "strategies": [{"rfe": KEY, "strat": KEY, "recommendation": "approve", "needs_attention": False}]}
    checker = validator.Checker()
    validator.check_keys(checker, result, {"type": "initiative-strategy"})
    assert checker.failures == []
    result["strategies"][0]["strat"] = "RHAISTRAT-42"
    validator.check_keys(checker, result, {"type": "initiative-strategy"})
    assert checker.failures == [f"RHAISTRAT-42 is not written on its own ticket {KEY}"]
    checker = validator.Checker()
    validator.check_keys(checker, result, {})  # an RFE run: RHAISTRAT-41 is no RFE (RHAISTRAT-42 may be a STRAT)
    assert len(checker.failures) == 3  # the input, acquired and pair keys


def test_initiative_results_publish_under_their_own_folder(tmp_path):
    publisher = module("initiative_publisher", ROOT / ".fullsend/shared/publish/push-results.py")
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / "strat-tasks").mkdir()
    (tmp_path / "strat-tasks" / f"{KEY}.md").write_text("strategy\n")
    run = publisher.organize_identified_run(tmp_path, "r1", "initiative-strategy")
    assert run == tmp_path.resolve() / "initiative-strategy/run-r1"
    assert (run / "strat-tasks" / f"{KEY}.md").read_text() == "strategy\n"
    assert not (tmp_path / "RHAISTRAT").exists()
    with pytest.raises(ValueError, match="invalid publication folder"):
        publisher.organize_identified_run(tmp_path, "r2", "../RHAISTRAT")


def test_write_guard_takes_an_initiative_as_its_own_input(monkeypatch):
    """RHAISTRAT holds Initiatives too: their writes are owned on the ticket itself, not via a Cloners link."""
    import jira_utils
    import strat_side_effects as effects
    owner = effects.owner_label("r1")
    monkeypatch.setattr(jira_utils, "get_issue", lambda *a, **k: {"fields": {
        "issuelinks": [], "labels": [owner, "strat-creator-processing"]}})
    data = {"run_id": "r1", "lock_owner": "r1", "acquired_keys": [KEY], "type": "initiative-strategy"}
    effects.check_owner("s", "u", "t", KEY, data)
    with pytest.raises(effects.UncertainWrite, match="no unique source RFE"):
        effects.check_owner("s", "u", "t", KEY, {**data, "type": "rfe-strategy"})


def test_stale_ticket_scope_follows_the_run_type(repo):
    """#93's per-ticket freshness scope: an Initiative strategy's source is the Initiative itself."""
    import strat_freshness
    data = json.loads((repo / "tmp/strat-input.json").read_text())
    assert strat_freshness.source_rfe(repo, KEY, data) == KEY
    rfe_run = {**data, "type": "rfe-strategy", "acquired_keys": ["RHAIRFE-1"]}
    assert strat_freshness.source_rfe(repo, "RHAIRFE-1", rfe_run) == "RHAIRFE-1"
    with pytest.raises(ValueError, match="outside acquired"):  # an RFE run reads source_rfe, which it lacks
        strat_freshness.source_rfe(repo, KEY, rfe_run)
