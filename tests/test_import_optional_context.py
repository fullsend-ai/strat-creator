def prepared(request, jira, monkeypatch):
    prepared = request.getfixturevalue("host")
    monkeypatch.chdir(prepared["tmp"])
    monkeypatch.delenv("STRAT_MANAGED_RUN", raising=False)
    monkeypatch.delenv("STRAT_EFFECTS_DIR", raising=False)
    jira.create(RFE, "Preserve current recovery guidance", "Use complete, current inputs.",
                labels=["strat-creator-3.8", "tech-reviewed"])
