def artifacts(root):
    return {str(path.relative_to(root)): path.read_bytes()
            for path in (root / "artifacts").rglob("*") if path.is_file()}


@pytest.mark.parametrize("relative", OPTIONAL)
def test_omitted_optional_context_stops_without_replacing_work(prepared, relative):
    root = prepared["target"]
    stale = root / relative
    stale.parent.mkdir(parents=True)
    text = "Local feedback of unknown ownership.\n"
    if relative == OPTIONAL[0]:
        text = f"# Comments: {RFE}\n\nNo comments found.\n\n" + text
    stale.write_text(text)
    task = root / f"artifacts/strat-tasks/{KEY}.md"
    task.parent.mkdir(parents=True, exist_ok=True)
    task.write_text("## Strategy (AI Generated by Agentic SDLC Pipeline)\nKeep existing refined work.\n")
    write_frontmatter(task, {"strat_id": KEY, "source_rfe": RFE, "jira_key": KEY, "title": "Current work",
                            "priority": "Major", "status": "Refined"}, "strat-task")
    before = artifacts(root)
    process = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert process.returncode != 0
    assert "optional context" in process.stderr and "reconcile" in process.stderr
    assert artifacts(root) == before
    assert not (root / f"tmp/strat-imports/{KEY}.json").exists()


@pytest.mark.parametrize("prepared", [True], indirect=True)
def test_managed_interrupted_import_refuses_stale_review_and_can_reconcile(prepared, jira):
    child = r'''
import os, signal, sys
from pathlib import Path
sys.path.insert(0, str(Path.cwd() / 'scripts'))
import import_strategy as importer
original = importer.publish_file
def stopped(source, target):
    original(source, target)
    if Path(target).resolve() == Path.cwd() / sys.argv[1]:
        os.kill(os.getpid(), signal.SIGKILL)
importer.publish_file = stopped
importer.import_strategy(sys.argv[2], sys.argv[3])
'''
    root = prepared["target"]
    first = cli(prepared, "-c", child, REVIEW, KEY, RFE)
    assert first.returncode == -signal.SIGKILL, first.stderr
    review = root / REVIEW
    before = artifacts(root)
    assert REVIEW in before
    attachment, = jira.get(KEY)["fields"]["attachment"]
    jira.request("DELETE", f"/rest/api/3/attachment/{attachment['id']}")
    retry = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert retry.returncode != 0 and "optional context" in retry.stderr
    assert artifacts(root) == before
    assert not (root / f"tmp/strat-imports/{KEY}.json").exists()
    # Simulate explicit operator reconciliation without deleting the evidence.
    saved = root / "tmp/reconciled-prior-review.md"
    review.rename(saved)
    recovered = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert recovered.returncode == 0, recovered.stderr
    record = json.loads((root / f"tmp/strat-imports/{KEY}.json").read_text())
    assert REVIEW not in record["files"] and not review.exists()
    assert saved.read_bytes() == before[REVIEW]
    created = cli(prepared, "scripts/strat_pipeline_state.py", "record-create")
    assert created.returncode == 0, created.stderr
    checked = cli(prepared, "scripts/strat_pipeline_state.py", "read")
    assert checked.returncode == 0, checked.stderr
    (prepared["tmp"] / "optional-recovery.json").write_text(json.dumps({
        "initial_exit": first.returncode, "refused_exit": retry.returncode, "refused_stderr": retry.stderr,
        "reconciled_exit": recovered.returncode, "record_create_exit": created.returncode,
        "freshness_exit": checked.returncode, "completion": record}, indent=2))


def test_completed_import_keeps_a_later_local_review(prepared):
    process = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert process.returncode == 0, process.stderr
    review = prepared["target"] / REVIEW
    review.parent.mkdir()
    review.write_text("Later local assessment; preserve this work.\n")
    before = artifacts(prepared["target"])
    again = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert again.returncode == 0, again.stderr
    assert json.loads(again.stdout)["already_imported"]
    assert artifacts(prepared["target"]) == before


