def test_pre_fix_import_receipt_does_not_bypass_optional_context_check(prepared):
    root = prepared["target"]
    first = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert first.returncode == 0, first.stderr
    receipt = root / f"tmp/strat-imports/{KEY}.json"
    data = json.loads(receipt.read_text())
    data["contract"] = "strat-import-v1"
    receipt.write_text(json.dumps(data))
    review = root / REVIEW
    review.parent.mkdir()
    review.write_text("Untracked prior feedback accepted by the old importer.\n")
    before = artifacts(root)
    retried = cli(prepared, "scripts/import_strategy.py", KEY, "--rfe", RFE)
    assert retried.returncode != 0 and "import completion identity" in retried.stderr
    assert artifacts(root) == before
    assert json.loads(receipt.read_text())["contract"] == "strat-import-v1"
