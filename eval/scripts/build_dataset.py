#!/usr/bin/env python3
"""Build the strat-creator eval dataset from real prod runs.

Source of truth: the `strat-pipeline-data` repo (the production data repo that
CI pushes to). Each timestamped run under `RHAISTRAT/<ts>/` contains, per
strategy:
  - strat-originals/RHAIRFE-<n>.md   — the approved-RFE business-need snapshot (INPUT)
  - strat-tasks/<strat>.md           — the produced refined strategy (reference OUTPUT)
  - strat-reviews/<strat>-review.md  — the scored review (reference SCORES)
  - pipeline-data.json               — structured per-strategy scores/metadata

For each curated RFE we reconstruct exactly what `strategy-create --dry-run`
(Path B) produces on disk — the strat-task STUB (verbatim Business Need + empty
Strategy section + Staff Engineer input + schema frontmatter) — so the eval's
cli-runner driver can hand it straight to `/strategy-refine` and `/strategy-review`,
faithfully reproducing the production create->refine->review handoff without any
live Jira (create is mechanical; the LLM-driven, quality-determining stages are
refine + review).

Output layout (one dir per case), consumed by eval/strat-refine.yaml (execution.steps):
  eval/dataset/cases/<case-id>/
    input.yaml            — rfe_key, strat_id, title, priority, size (drives the driver + judges)
    stub.md               — strategy-create output (refine's input); staged to artifacts/strat-tasks/<strat_id>.md
    rfe-original.md       — RFE Business Need snapshot; staged to artifacts/strat-originals/<rfe_key>.md
    rfe-comments.md       — removed-implementation-context comments (optional; refine Source 1 fallback)
    reference/strategy.md — the prod-produced refined strategy (calibration / regression only)
    reference/scores.yaml — the prod rubric scores (calibration / regression only)
    annotations.yaml      — expected_scores + expected_recommendation + tags (judge context)

The work type (--type, default rfe-strategy) supplies the input key grammar, the
Business Need heading, the source field, whether the strategy lives on the input
ticket itself (relation self: the strat id is the key) and the default --out (its
descriptor's eval.dataset). Initiative strategies: --type initiative-strategy, from
the data repo's initiative-strategy/ folder, every case found (no curated list yet).

Usage:
    python3 eval/scripts/build_dataset.py                       # default data repo, curated set
    python3 eval/scripts/build_dataset.py --type initiative-strategy
    python3 eval/scripts/build_dataset.py --data-repo /path/to/strat-pipeline-data/RHAISTRAT
    python3 eval/scripts/build_dataset.py --out eval/dataset/cases --force
"""

import argparse
import glob
import json
import os
import re
import subprocess
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FRONTMATTER = os.path.join(REPO_ROOT, "scripts", "frontmatter.py")
sys.path.insert(0, os.path.join(REPO_ROOT, "scripts"))

import type_registry  # noqa: E402

PRIORITY_ENUM = {"Blocker", "Critical", "Major", "Normal", "Minor", "Undefined"}


def key_re(desc):
    """The type's canonical input-key form (rfe-strategy: ``^RHAIRFE-[0-9]+$``). Keys are interpolated
    into case directory names, so a non-conforming value (e.g. one containing ../) is rejected before
    path composition."""
    return re.compile("^(" + "|".join(re.escape(p) for p in desc.get("inputs.0.jira.key_prefixes")) + ")[0-9]+$")


# Curated ~24 anchors spanning the full quality range, all sizes, and the scarce
# high-value cases (zero-dimension / reject). Scores shown are the prod reference
# at selection time; the script resolves each RFE's LATEST complete triple, so the
# live reference may differ slightly (that's fine — annotations use the resolved value).
CURATED = [
    # 8/8 ceiling
    "RHAIRFE-912", "RHAIRFE-1433", "RHAIRFE-1436",
    # 7/8
    "RHAIRFE-709", "RHAIRFE-795", "RHAIRFE-911", "RHAIRFE-2172",
    # 6/8 (approve floor)
    "RHAIRFE-1131", "RHAIRFE-1061", "RHAIRFE-1161",
    # 5/8 (revise band)
    "RHAIRFE-1160", "RHAIRFE-1165", "RHAIRFE-728",
    # 4/8 incl. zero-dimension + XL
    "RHAIRFE-629", "RHAIRFE-1676", "RHAIRFE-1706", "RHAIRFE-2675", "RHAIRFE-2750",
    # 3/8 zero-dimension
    "RHAIRFE-1293", "RHAIRFE-127",
    # reject / multi-zero (scarce, high value)
    "RHAIRFE-1056", "RHAIRFE-1712", "RHAIRFE-1753", "RHAIRFE-1754",
]

STRATEGY_SECTION = """## Strategy (AI Generated by Agentic SDLC Pipeline)
<!-- DO NOT manually modify this section. It is generated and maintained by the pipeline. -->
<!-- Use the Staff Engineer / SME Input section below to provide corrections or guidance. -->
<!-- To be filled by /strategy-refine -->
"""

STAFF_SECTION = """## Staff Engineer / SME Input

*Add technical corrections, architectural direction, component preferences, or domain expertise below. Write in declarative, cumulative form — statements that remain valid across refinement iterations. This input takes priority over architecture context when they conflict. After review: address findings, then remove the needs-attention label from Jira.*
"""


def slugify(text, maxlen=48):
    s = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    return s[:maxlen].strip("-") or "untitled"


def norm_priority(p):
    return p if p in PRIORITY_ENUM else "Undefined"


def rfe_num(rfe_key):
    m = re.search(r"(\d+)$", rfe_key)
    return m.group(1) if m else rfe_key


def load_latest_triples(data_repo):
    """Return {rfe_key: dict} for the LATEST run that has a complete on-disk triple."""
    runs = sorted(glob.glob(os.path.join(data_repo, "2026*", "pipeline-data.json")))
    best = {}
    for pj in runs:
        run_dir = os.path.dirname(pj)
        ts = os.path.basename(run_dir)
        try:
            with open(pj, encoding="utf-8") as fh:
                d = json.load(fh)
        except (OSError, json.JSONDecodeError) as e:
            # Silently skipping the newest run would quietly fall back to an older
            # one and emit stale reference scores, so make the skip visible.
            print(f"  WARN: skipping unreadable run metadata {pj}: {e}", file=sys.stderr)
            continue
        items = d if isinstance(d, list) else (d.get("strategies") or d.get("data") or [])
        if not isinstance(items, list):
            continue
        for e in items:
            rfe = e.get("source_rfe")
            sid = e.get("strat_id")
            scores = e.get("scores") or {}
            if not rfe or not sid or scores.get("total") is None:
                continue
            orig = glob.glob(os.path.join(run_dir, "strat-originals", f"{rfe}*.md"))
            orig = [p for p in orig if "-comments" not in os.path.basename(p)]
            task = glob.glob(os.path.join(run_dir, "strat-tasks", f"{sid}*.md"))
            rev = glob.glob(os.path.join(run_dir, "strat-reviews", f"{sid}*review*.md"))
            if not (orig and task and rev):
                continue
            if rfe not in best or ts > best[rfe]["ts"]:
                comments = glob.glob(os.path.join(run_dir, "strat-originals", f"{rfe}*-comments.md"))
                best[rfe] = {
                    "ts": ts, "entry": e, "original": orig[0], "strategy": task[0],
                    "review": rev[0], "comments": comments[0] if comments else None,
                }
    return best


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def set_frontmatter(path, **fields):
    # Explicit --schema-type: the path lives under eval/dataset/, not artifacts/,
    # so frontmatter.py cannot auto-detect the schema from the path.
    args = [sys.executable, FRONTMATTER, "set", "--schema-type", "strat-task", path]
    for k, v in fields.items():
        args.append(f"{k}={v}")
    r = subprocess.run(args, cwd=REPO_ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"frontmatter set failed for {path}:\n{r.stdout}\n{r.stderr}")


def build_case(rfe_key, tri, out_root, force, desc):
    e = tri["entry"]
    scores = e.get("scores") or {}
    total = scores.get("total")
    title = e.get("title") or rfe_key
    priority = norm_priority(e.get("priority"))
    size = e.get("size")
    # A type that runs on its own ticket (relation self) writes the strategy under the input's key,
    # with --dry-run too; a cloning type's dry run names it STRAT-<n> with no key.
    same_ticket = desc.get("inputs.0.relation.kind") == "self"
    strat_id = rfe_key if same_ticket else f"STRAT-{rfe_num(rfe_key)}"

    # rfe_key reaches here from --keys or the data repo and is used to compose a
    # path, so reject anything that is not the canonical form (a value containing
    # ../ would otherwise escape out_root).
    if not key_re(desc).match(rfe_key):
        print(f"  SKIP {rfe_key!r} (not a canonical {desc.name} input key)", file=sys.stderr)
        return None

    case_id = f"{rfe_key}-{slugify(title)}"
    case_dir = os.path.join(out_root, case_id)
    if os.path.isdir(case_dir) and not force:
        print(f"  SKIP {case_id} (exists; use --force)")
        return None
    os.makedirs(os.path.join(case_dir, "reference"), exist_ok=True)

    rfe_body = read(tri["original"]).strip()

    # 1) rfe-original.md — Business Need snapshot (staged to artifacts/strat-originals)
    write(os.path.join(case_dir, "rfe-original.md"), rfe_body + "\n")

    # 2) rfe-comments.md — removed-implementation-context (refine Source 1 fallback).
    #    Always written (even if empty) so the strat-refine.yaml workspace whitelist is stable.
    if tri["comments"]:
        write(os.path.join(case_dir, "rfe-comments.md"), read(tri["comments"]))
    else:
        write(os.path.join(case_dir, "rfe-comments.md"), f"# Comments: {rfe_key}\n\nNo comments found.\n")

    # 3) stub.md — exactly what strategy-create --dry-run Path B emits (refine's input)
    stub_body = (
        f"{desc.get('pipeline.section_ownership.0.heading')}\n"
        f"{rfe_body}\n\n"
        f"{STRATEGY_SECTION}\n"
        f"{STAFF_SECTION}"
    )
    stub_path = os.path.join(case_dir, "stub.md")
    write(stub_path, stub_body)
    fields = {"strat_id": strat_id, "title": title, desc.get("inputs.0.source_ref_field"): rfe_key,
              "jira_key": rfe_key if same_ticket else "null", "priority": priority, "status": "Draft"}
    if desc.name != type_registry.LEGACY_DEFAULT_TYPE:
        # strategy-create stamps it, and it picks the schema; rfe-strategy cases stay as they were built
        fields["type"] = desc.name
    set_frontmatter(stub_path, **fields)

    # 4) reference/ — prod outputs (calibration / regression only; never fed to refine)
    write(os.path.join(case_dir, "reference", "strategy.md"), read(tri["strategy"]))
    ref_scores = {
        "feasibility": scores.get("feasibility"),
        "testability": scores.get("testability"),
        "scope": scores.get("scope"),
        "architecture": scores.get("architecture"),
        "total": total,
        "recommendation": e.get("recommendation"),
        "source_run": tri["ts"],
        "reference_strat_id": e.get("strat_id"),
    }
    write(os.path.join(case_dir, "reference", "scores.yaml"), to_yaml(ref_scores))

    # 5) input.yaml — driver + template inputs
    input_data = {
        "rfe_key": rfe_key,
        "strat_id": strat_id,
        "title": title,
        "priority": priority,
        "size": size if size else "unknown",
    }
    write(os.path.join(case_dir, "input.yaml"), to_yaml(input_data))

    # 6) annotations.yaml — expected outcomes for calibration judges / analysis
    has_zero = any(scores.get(k) == 0 for k in ("feasibility", "testability", "scope", "architecture"))
    difficulty = "hard" if (total is not None and total <= 4) else ("medium" if total <= 6 else "easy")
    tags = [f"size:{size or 'unknown'}", f"band:{total}", e.get("recommendation") or "unknown"]
    if has_zero:
        tags.append("zero-dimension")
    annotations = {
        "expected_scores": {
            "feasibility": scores.get("feasibility"),
            "testability": scores.get("testability"),
            "scope": scores.get("scope"),
            "architecture": scores.get("architecture"),
            "total": total,
        },
        "expected_recommendation": e.get("recommendation"),
        "expected_size": size if size else "unknown",
        "score_tolerance": 1,
        "difficulty": difficulty,
        "tags": tags,
        "note": (
            "expected_* are the production reference (single-sample assess-strat scorer). "
            "Use as a calibration anchor, not a hard gate — score_tolerance applies."
        ),
    }
    write(os.path.join(case_dir, "annotations.yaml"), to_yaml(annotations))

    print(f"  OK   {case_id:<60} total={total}/8 {e.get('recommendation'):<7} size={size} run={tri['ts']}")
    return {"case_id": case_id, "rfe": rfe_key, "total": total,
            "rec": e.get("recommendation"), "size": size}


def to_yaml(obj):
    try:
        import yaml
        return yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, default_flow_style=False)
    except Exception:
        return json.dumps(obj, indent=2) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--type", default=type_registry.LEGACY_DEFAULT_TYPE,
                    help="Work type (default: rfe-strategy)")
    ap.add_argument("--data-repo",
                    help="Path to the type's strat-pipeline-data folder (default: "
                         "/tmp/strat-pipeline-data/RHAISTRAT for rfe-strategy, "
                         "/tmp/strat-pipeline-data/<type> otherwise: strat-pipeline's RESULTS_SUBDIR)")
    ap.add_argument("--out", help="Case directory (default: the type's eval.dataset)")
    ap.add_argument("--force", action="store_true", help="Overwrite existing case dirs")
    ap.add_argument("--keys", nargs="*",
                    help="Override the key list (rfe-strategy: the curated list; else every key found)")
    args = ap.parse_args()
    desc = type_registry.load().get(args.type)
    legacy = desc.name == type_registry.LEGACY_DEFAULT_TYPE
    args.data_repo = args.data_repo or f"/tmp/strat-pipeline-data/{'RHAISTRAT' if legacy else desc.name}"
    args.out = args.out or os.path.join(REPO_ROOT, desc.get("eval.dataset"))

    if not os.path.isdir(args.data_repo):
        print(f"ERROR: data repo not found: {args.data_repo}\n"
              f"Clone the internal strat-pipeline-data repo first (ask the "
              f"strat-pipeline maintainers for its location), then point at it:\n"
              f"  python3 eval/scripts/build_dataset.py --data-repo "
              f"<checkout>/RHAISTRAT", file=sys.stderr)
        return 2

    print(f"Scanning {args.data_repo} for complete RFE->strategy->score triples ...")
    triples = load_latest_triples(args.data_repo)
    print(f"Found {len(triples)} unique RFEs with a complete on-disk triple.\n")

    keys = args.keys or (CURATED if legacy else sorted(triples))
    os.makedirs(args.out, exist_ok=True)
    built, missing = [], []
    for rfe in keys:
        tri = triples.get(rfe)
        if not tri:
            missing.append(rfe)
            print(f"  MISS {rfe} — no complete triple found in data repo")
            continue
        row = build_case(rfe, tri, args.out, args.force, desc)
        if row:
            built.append(row)

    print(f"\nBuilt {len(built)} cases -> {args.out}")
    if missing:
        print(f"Missing {len(missing)}: {', '.join(missing)}")
        print("  (pick replacements from the same score band; re-run with --keys)")
    # distribution summary
    from collections import Counter
    bands = Counter(r["total"] for r in built)
    sizes = Counter(r["size"] for r in built)
    print(f"Score bands: {dict(sorted(bands.items()))}")
    print(f"Sizes: {dict(sizes)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
